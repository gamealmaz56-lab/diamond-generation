import re

def process_index(filepath):
    with open(filepath, 'r') as f:
        html = f.read()

    # Fix clumsy subtitle in 4 pillars section
    html = html.replace('Метод «4 Опоры»: Восстановите ресурс, верните ясность ума и выйдите из кризиса без выгорания', 
                        'Фундамент вашей энергии. Четыре опоры, на которых держится бизнес и жизнь')
                        
    html = html.replace('Как работает методология', 'Архитектура метода')

    html = html.replace('Результаты тех, кто прошёл программу', 'Кейсы: бизнес и жизнь после восстановления')

    with open(filepath, 'w') as f:
        f.write(html)
    print(f"Updated {filepath}")

